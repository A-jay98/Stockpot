// Builds the food-icon sprites from the registry: `pnpm icons`.
// Output is committed and CI regenerates it (`make gen`), so it must be deterministic.
// Each sprite holds only registry keys as <symbol id="fi-<key>">, so there is no runtime CDN
// and no unused glyphs. Fluent comes in two styles (high-contrast mono, flat colour); the
// Tabler fallbacks are mono in both.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'src/ui/food-icons')
const registry = JSON.parse(readFileSync(join(dir, 'registry.json'), 'utf8'))

const load = (pkg) => {
  const data = JSON.parse(readFileSync(require.resolve(`@iconify-json/${pkg}/icons.json`), 'utf8'))
  return {
    width: data.width ?? 16,
    height: data.height ?? 16,
    get(name) {
      const alias = data.aliases?.[name]
      if (alias && Object.keys(alias).some((k) => k !== 'parent')) {
        throw new Error(`${pkg}:${name} is a transformed alias (flip/rotate/size); use its parent`)
      }
      const icon = data.icons[alias ? alias.parent : name]
      if (!icon) return null
      return { width: data.width ?? 16, height: data.height ?? 16, ...icon }
    },
  }
}

const sets = {
  'high-contrast': { fe: load('fluent-emoji-high-contrast'), tb: load('tabler') },
  flat: { fe: load('fluent-emoji-flat'), tb: load('tabler') },
}

// Iconify bodies carry their own ids (clip paths, gradients) that repeat across icons; once
// concatenated into one document they would resolve to the first definition. Namespace per symbol.
function scopeIds(key, body) {
  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1])
  let out = body
  for (const id of new Set(ids)) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    out = out
      .replace(new RegExp(`\\bid="${esc}"`, 'g'), `id="fi-${key}-${id}"`)
      .replace(new RegExp(`url\\(#${esc}\\)`, 'g'), `url(#fi-${key}-${id})`)
      .replace(new RegExp(`href="#${esc}"`, 'g'), `href="#fi-${key}-${id}"`)
  }
  return out
}

const read = (f) => readFileSync(join(dir, 'licenses', f), 'utf8').trim()
const fluentLicense = read('fluent-emoji.LICENSE')
const tablerLicense = read('tabler.LICENSE')
const header = `<!--
Generated by web/scripts/build-icons.mjs. Do not edit.
Fluent Emoji (https://github.com/microsoft/fluentui-emoji), Copyright (c) Microsoft Corporation, MIT.
Tabler Icons (https://github.com/tabler/tabler-icons), Copyright (c) 2020-2026 Pawel Kuna, MIT.
Full licence texts: /licenses.txt
-->
`

let failed = false
mkdirSync(join(dir, 'sprites'), { recursive: true })
for (const [style, byset] of Object.entries(sets)) {
  const symbols = []
  for (const [key, entry] of Object.entries(registry)) {
    const icon = byset[entry.set]?.get(entry.name)
    if (!icon) {
      console.error(`${style}: registry key "${key}" -> ${entry.set}:${entry.name} not found`)
      failed = true
      continue
    }
    symbols.push(
      `<symbol id="fi-${key}" viewBox="0 0 ${icon.width} ${icon.height}">${scopeIds(key, icon.body)}</symbol>`,
    )
  }
  const svg = `${header}<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">\n${symbols.join('\n')}\n</svg>\n`
  writeFileSync(join(dir, 'sprites', `${style}.svg`), svg)
  console.log(`${style}: ${symbols.length} icons, ${(svg.length / 1024).toFixed(0)} KB`)
}
if (failed) process.exit(1)

// Shipped with the app (web/public) so the notices travel with the sprites.
const publicDir = join(root, 'public')
mkdirSync(publicDir, { recursive: true })
writeFileSync(
  join(publicDir, 'licenses.txt'),
  `Stockpot open-source notices: food icons\n\n=== Fluent Emoji (Microsoft) ===\nhttps://github.com/microsoft/fluentui-emoji\n\n${fluentLicense}\n\n=== Tabler Icons ===\nhttps://github.com/tabler/tabler-icons\n\n${tablerLicense}\n`,
)
